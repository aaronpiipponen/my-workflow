"""Generate repository subagents for OpenCode.

Canonical prompts live in ``AGENT-INSTRUCTIONS/SUBAGENTS/<name>.md`` (shipped by the
workflow repository) and ``AGENT-INSTRUCTIONS/LOCAL/roles/<name>.md`` (roles a workspace adds
for itself). Model assignments live in the workspace's ``AGENT-INSTRUCTIONS/LOCAL/models.json``. Permission patterns live in ``LOCAL/workflow.toml`` as named capabilities; a role
names a capability and the generator expands it, including each pattern's absolute forms in the
workspace root and in every worktree.

The agents are stamped into the workspace root's ``.opencode/agents/``, which OpenCode also reads
for sessions in the worktrees below it.

Generated files must not be edited directly.

Usage, from the workspace root or any of its worktrees:
    python AGENT-INSTRUCTIONS/SUBAGENTS/gen_agents.py
    python AGENT-INSTRUCTIONS/SUBAGENTS/gen_agents.py --check
"""

import json
import os
import re
import sys
import tomllib

SRC_DIR = os.path.dirname(os.path.abspath(__file__))
# SUBAGENTS links into the workflow repository, so the root comes from the AGENT-INSTRUCTIONS
# folder the script was reached through, resolved past a worktree's link to the root's real folder.
REPO_ROOT = os.path.dirname(os.path.realpath(os.path.dirname(SRC_DIR)))
LOCAL_DIR = os.path.join(REPO_ROOT, "AGENT-INSTRUCTIONS", "LOCAL")
LOCAL_MODELS = os.path.join(LOCAL_DIR, "models.json")
WORKFLOW = os.path.join(LOCAL_DIR, "workflow.toml")
OPENCODE_DIR = os.path.join(REPO_ROOT, ".opencode", "agents")


def _gen_note(name):
    return (
        "<!-- GENERATED by AGENT-INSTRUCTIONS/SUBAGENTS/gen_agents.py from "
        f"AGENT-INSTRUCTIONS/SUBAGENTS/{name}.md - DO NOT EDIT. -->"
    )


def _source_path(name):
    """A shipped role wins over a local role of the same name, so a workspace can shadow nothing."""
    shipped = os.path.join(SRC_DIR, f"{name}.md")
    if os.path.exists(shipped):
        return shipped
    local = os.path.join(LOCAL_DIR, "roles", f"{name}.md")
    if os.path.exists(local):
        return local
    raise ValueError(f"no source for role '{name}'")


def agent_names():
    names = {
        filename[:-3]
        for filename in os.listdir(SRC_DIR)
        if filename.endswith(".md") and filename != "README.md"
    }
    roles_dir = os.path.join(LOCAL_DIR, "roles")
    if os.path.isdir(roles_dir):
        names |= {filename[:-3] for filename in os.listdir(roles_dir) if filename.endswith(".md")}
    return sorted(names)


def _parse_source(name):
    path = _source_path(name)
    with open(path, encoding="utf-8") as source:
        text = source.read()
    if not text.startswith("---"):
        raise ValueError(f"{name}.md: missing frontmatter")
    _, frontmatter, body = text.split("---", 2)
    metadata = {}
    for line in frontmatter.strip().splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            metadata[key.strip()] = value.strip()
    if "description" not in metadata:
        raise ValueError(f"{name}.md: frontmatter missing 'description'")
    return metadata, body.strip()


def _delegates_for(metadata):
    return [value.strip() for value in metadata.get("delegates", "").split(",") if value.strip()]


PARTIAL_MARKER = re.compile(r"^<!-- partial: ([a-z0-9-]+) -->$", re.M)


def _apply_partials(name, body):
    """Replace each ``<!-- partial: id -->`` marker with the shared block it names.

    A partial is workflow convention that must read identically in every role carrying it
    (orchestrator authority, reviewer tool-call discipline). The marker keeps one tracked
    copy under ``partials/`` and keeps each role's own section order intact.
    """

    def replace(match):
        partial = match.group(1)
        path = os.path.join(SRC_DIR, "partials", f"{partial}.md")
        if not os.path.exists(path):
            raise ValueError(f"{name}.md: unknown partial '{partial}'")
        with open(path, encoding="utf-8") as source:
            return source.read().strip()

    return PARTIAL_MARKER.sub(replace, body)


def _load_workflow():
    if not os.path.exists(WORKFLOW):
        raise SystemExit(
            f"{os.path.relpath(WORKFLOW, REPO_ROOT)} is missing. Run setup/setup-workspace.py for this "
            "workspace, or copy setup/local.example/workflow.toml into AGENT-INSTRUCTIONS/LOCAL/."
        )
    with open(WORKFLOW, "rb") as source:
        return tomllib.load(source)


def _capability(name, kind, table):
    """Return one named capability as (allow, deny) lists, validated."""
    section = table.get(kind, {}).get(name)
    if not isinstance(section, dict):
        raise ValueError(f"workflow.toml: no [{kind}.{name}] capability")
    allow = [str(value) for value in section.get("allow", [])]
    deny = [str(value) for value in section.get("deny", [])]
    if allow and deny:
        raise ValueError(f"workflow.toml: [{kind}.{name}] declares allow and deny together")
    if not allow and not deny:
        raise ValueError(f"workflow.toml: [{kind}.{name}] declares neither allow nor deny")
    if deny and "*" in deny:
        raise ValueError(f"workflow.toml: [{kind}.{name}] cannot deny '*'")
    return allow, deny


def _expanded(patterns):
    """Yield each pattern plus its absolute forms, which OpenCode matches separately.

    A relative pattern names a path in the session's worktree, or in the root for the instruction
    tree, whose real files OpenCode reports by their canonical path.
    """
    for pattern in patterns:
        yield pattern
        if not pattern.startswith(("/", "~", "*")):
            yield os.path.join(REPO_ROOT, pattern)
            yield os.path.join(REPO_ROOT, "*", pattern)


def _permission_rule(action, resource, effect):
    return [
        f"  - action: {action}",
        f'    resource: "{resource}"',
        f"    effect: {effect}",
    ]


def _write_rules(name, metadata, workflow):
    """Build the edit rules for a writing role from its single write capability."""
    capability = metadata.get("write")
    if not capability:
        if metadata.get("access") != "read-only":
            raise ValueError(f"{name}.md: a writing role must declare 'write: <capability>'")
        return []
    if metadata.get("access") == "read-only":
        raise ValueError(f"{name}.md: 'write' is invalid with 'access: read-only'")
    allow, deny = _capability(capability, "write", workflow)
    if allow == ["*"]:
        # Unrestricted writes need no rule: OpenCode allows the edit action by default.
        return []
    # "edit" carries the edit, write and patch tools in V2. The same policy is emitted for the
    # "write" action as well, so a deployment that exposes it separately stays inside the gate.
    rules = []
    for action in ("edit", "write"):
        if allow:
            rules.extend(_permission_rule(action, "*", "deny"))
            for pattern in _expanded(allow):
                rules.extend(_permission_rule(action, pattern, "allow"))
        else:
            rules.extend(_permission_rule(action, "*", "allow"))
            for pattern in _expanded(deny):
                rules.extend(_permission_rule(action, pattern, "deny"))
    return rules


def _shell_rules(name, metadata, workflow, readonly):
    capability = metadata.get("shell")
    if not capability:
        if readonly:
            return _permission_rule("shell", "*", "deny")
        return []
    allow, deny = _capability(capability, "shell", workflow)
    rules = []
    if allow:
        if allow != ["*"]:
            rules.extend(_permission_rule("shell", "*", "deny"))
        for pattern in allow:
            rules.extend(_permission_rule("shell", pattern, "allow"))
    else:
        rules.extend(_permission_rule("shell", "*", "allow"))
        for pattern in deny:
            rules.extend(_permission_rule("shell", pattern, "deny"))
    return rules


def render_opencode(name, metadata, body, assignment, workflow):
    readonly = metadata.get("access") == "read-only"
    body = _apply_partials(name, body)
    model = assignment["model"]
    if assignment.get("variant"):
        model = f"{assignment['model']}#{assignment['variant']}"
    mode = metadata.get("mode", "subagent")
    if mode not in {"primary", "subagent", "all"}:
        raise ValueError(f"{name}.md: unsupported mode '{mode}'")
    frontmatter = [
        f"description: {metadata['description']}",
        f"mode: {mode}",
        f"model: {model}",
    ]
    # OpenCode evaluates an ordered rule list and the last matching rule wins, so every
    # catch-all deny precedes its specific allows.
    permissions = []
    if readonly:
        permissions.extend(_permission_rule("edit", "*", "deny"))
        permissions.extend(_permission_rule("write", "*", "deny"))
    else:
        permissions.extend(_write_rules(name, metadata, workflow))
    permissions.extend(_shell_rules(name, metadata, workflow, readonly))
    external = metadata.get("external")
    if external:
        allow, _ = _capability(external, "external", workflow)
        for directory in allow:
            permissions.extend(_permission_rule("external_directory", directory, "allow"))
    # Every agent is denied subagents by default; only declared delegates are allowed.
    permissions.extend(_permission_rule("subagent", "*", "deny"))
    for delegate in _delegates_for(metadata):
        permissions.extend(_permission_rule("subagent", delegate, "allow"))
    frontmatter.append("permissions:")
    frontmatter.extend(permissions)
    return "---\n" + "\n".join(frontmatter) + "\n---\n" + _gen_note(name) + "\n\n" + body + "\n"


def _load_models():
    if not os.path.exists(LOCAL_MODELS):
        raise SystemExit(
            f"{os.path.relpath(LOCAL_MODELS, REPO_ROOT)} is missing. Run setup/setup-workspace.py for this "
            "workspace, or copy setup/local.example/models.json into AGENT-INSTRUCTIONS/LOCAL/."
        )
    with open(LOCAL_MODELS, encoding="utf-8") as source:
        return json.load(source)


def _assignment_for(models, tool, name):
    table = models.get(tool, {})
    if name not in table:
        raise ValueError(f"models: no {tool} assignment for agent '{name}'")
    assignment = table[name]
    if isinstance(assignment, str):
        return {"model": assignment}
    if not isinstance(assignment, dict) or not isinstance(assignment.get("model"), str):
        raise ValueError(f"models: invalid {tool} assignment for agent '{name}'")
    unknown = set(assignment) - {"model", "variant"}
    if unknown:
        raise ValueError(
            f"models: unsupported {tool} assignment keys for agent '{name}': "
            f"{', '.join(sorted(unknown))}"
        )
    if "variant" in assignment and not isinstance(assignment["variant"], str):
        raise ValueError(f"models: variant for agent '{name}' must be a string")
    return assignment


def _targets():
    models = _load_models()
    workflow = _load_workflow()
    for name in agent_names():
        metadata, body = _parse_source(name)
        yield (
            os.path.join(OPENCODE_DIR, f"{name}.md"),
            render_opencode(
                name, metadata, body, _assignment_for(models, "opencode", name), workflow
            ),
        )


def orphaned_files():
    """Generated agents whose source no longer exists, left behind by a removed or renamed role."""
    if not os.path.isdir(OPENCODE_DIR):
        return []
    planned = {os.path.basename(path) for path, _ in _targets()}
    return sorted(
        os.path.join(OPENCODE_DIR, name)
        for name in os.listdir(OPENCODE_DIR)
        if name.endswith(".md") and name not in planned
    )


def generate():
    """Stamp every agent file whose content differs; return how many were written.

    OpenCode reloads an agent when its file changes, so an unchanged file is left untouched.
    """
    os.makedirs(OPENCODE_DIR, exist_ok=True)
    for path in orphaned_files():
        os.remove(path)
    stale = {path for path, _ in stale_files()}
    count = 0
    for path, content in _targets():
        if path in stale:
            with open(path, "w", encoding="utf-8") as target:
                target.write(content)
            count += 1
    return count


def stale_files():
    stale = []
    for path, content in _targets():
        if not os.path.exists(path):
            stale.append((path, "missing"))
            continue
        with open(path, encoding="utf-8") as target:
            if target.read() != content:
                stale.append((path, "out of date"))
    return stale


def main(argv):
    if "--check" in argv:
        for path in orphaned_files():
            print(f"ORPHANED: {os.path.relpath(path, REPO_ROOT)} (its source is gone)")
        stale = stale_files()
        for path, reason in stale:
            print(f"STALE: {os.path.relpath(path, REPO_ROOT)} ({reason})")
        return 1 if stale or orphaned_files() else 0
    count = generate()
    print(f"Stamped {count} changed agent file(s) of {len(agent_names())} agent(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
